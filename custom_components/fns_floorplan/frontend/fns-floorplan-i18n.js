function pick(l) { l = String(l || "").slice(0, 2).toLowerCase(); return STRINGS[l] ? l : "en"; }
// called from every `set hass` with hass.locale?.language || hass.language; true when the language changed
export function setLang(l) { const n = pick(l); const changed = n !== lang; lang = n; return changed; }
export const getLang = () => lang;
// t("key", {n: 3}) replaces {n}; a missing key falls back to English, then to the key itself
export function t(key, vars) {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return s;
}
